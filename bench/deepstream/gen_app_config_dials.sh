#!/usr/bin/env bash
# The latency-tuned deepstream-app config with the two capacity dials PyCamTRT exposes:
#   INTERVAL  nvinfer `interval` on the primary engine: infer every (INTERVAL+1)-th frame  (= PyCamTRT skip - 1)
#   INTRA     1 = `intra-decode-enable` on every source: the decoder outputs keyframes only (= PyCamTRT decode="key")
# Usage: ./gen_app_config_dials.sh N PREFIX INTERVAL INTRA   -> configs/app_<PREFIX><N>_tuned_i<INTERVAL>_k<INTRA>.txt
set -euo pipefail
N=${1:?usage: gen_app_config_dials.sh N PREFIX INTERVAL INTRA}; PREFIX=${2:-cam}; INTERVAL=${3:-0}; INTRA=${4:-0}
OUT="$(dirname "$0")/configs/app_${PREFIX}${N}_tuned_i${INTERVAL}_k${INTRA}.txt"
{
cat <<EOT
# Generated by gen_app_config_dials.sh $N $PREFIX $INTERVAL $INTRA - latency-tuned + dials.
[application]
enable-perf-measurement=1
perf-measurement-interval-sec=2

[tiled-display]
enable=0

EOT
for i in $(seq 1 "$N"); do
cat <<EOT
[source$((i-1))]
enable=1
type=4
uri=rtsp://127.0.0.1:8554/${PREFIX}${i}
latency=30
num-sources=1
intra-decode-enable=${INTRA}

EOT
done
cat <<EOT
[streammux]
gpu-id=0
live-source=1
batch-size=${N}
batched-push-timeout=5000
attach-sys-ts=1
width=1280
height=720
enable-padding=0
nvbuf-memory-type=0

[primary-gie]
enable=1
gpu-id=0
gie-unique-id=1
interval=${INTERVAL}
config-file=pgie_plates_fp16.txt

[secondary-gie0]
enable=1
gpu-id=0
gie-unique-id=2
operate-on-gie-id=1
config-file=sgie_lprnet_fp16.txt

[osd]
enable=0

[sink0]
enable=1
type=1
sync=0
EOT
} > "$OUT"
echo "wrote $OUT"
