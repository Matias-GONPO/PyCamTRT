#!/usr/bin/env bash
# Latency-tuned deepstream-app config generator. Differences from
# gen_app_config.sh (the idiomatic-default generator):
#   - fp16 GIEs (network-mode=2) — matches CORDERO's fp16 stage-1, the
#     single biggest latency lever (halves inference).
#   - streammux batched-push-timeout 5 ms (was 33 ms) — closes partial
#     batches sooner; helps low-N latency, harmless at N=16 where a full
#     batch fills in ~2 ms.
#   - RTSP source latency=30 ms jitter buffer (was 100 ms) — trims
#     source-delivery latency; live source, low jitter on localhost farm.
#   - attach-sys-ts=1, sync=0 — timestamp at arrival, never block on QoS.
# Usage: ./gen_app_config_tuned.sh N [prefix]
set -euo pipefail
N=${1:?usage: gen_app_config_tuned.sh N [prefix]}
PREFIX=${2:-plate}
OUT="$(dirname "$0")/configs/app_${PREFIX}${N}_tuned.txt"

{
cat <<EOF
# Generated by gen_app_config_tuned.sh $N $PREFIX — latency-tuned.
[application]
enable-perf-measurement=1
perf-measurement-interval-sec=2

[tiled-display]
enable=0

EOF

for i in $(seq 1 "$N"); do
cat <<EOF
[source$((i-1))]
enable=1
type=4
uri=rtsp://127.0.0.1:8554/${PREFIX}${i}
latency=30
num-sources=1

EOF
done

cat <<EOF
[streammux]
gpu-id=0
live-source=1
batch-size=${N}
batched-push-timeout=5000
attach-sys-ts=1
width=1280
height=720
enable-padding=0
nvbuf-memory-type=0

[primary-gie]
enable=1
gpu-id=0
gie-unique-id=1
config-file=pgie_plates_fp16.txt

[secondary-gie0]
enable=1
gpu-id=0
gie-unique-id=2
operate-on-gie-id=1
config-file=sgie_lprnet_fp16.txt

[osd]
enable=0

[sink0]
enable=1
type=1
sync=0
EOF
} > "$OUT"
echo "wrote $OUT"
